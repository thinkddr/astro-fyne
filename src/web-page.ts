import { join, relative, resolve, sep } from "node:path";
import { generatedText, type Artifact } from "./artifacts.ts";

export interface WebPageOptions {
  out: string;
  name: string;
  page?: boolean;
}

export function requireWebPage(direction: "native" | "web", page?: boolean) {
  if (page && direction !== "web")
    throw new Error("--page requires to-web; omit it when converting to Fyne.");
}

export function webPageOutput(options: WebPageOptions): string {
  return resolve(
    options.out,
    ...(options.page ? [`_${options.name}-web`] : []),
  );
}

/** Page-mode action paths start at the selected page directory. */
export function webPageActionsModule(
  options: WebPageOptions,
  module: string | undefined,
  consumer: string,
): string | undefined {
  if (!options.page || !module?.startsWith(".")) return module;
  const path = relative(consumer, resolve(options.out, module))
    .split(sep)
    .join("/");
  return path.startsWith(".") ? path : `./${path}`;
}

/** Include the entry point in the same preflight as every generated dependency. */
export function planWebPage(
  options: WebPageOptions,
  artifacts: Artifact[],
  document = false,
): Artifact[] {
  if (!options.page) return artifacts;
  const content = `---
// Code generated by astro-fyne. DO NOT EDIT.
// SPDX-License-Identifier: Apache-2.0
import Page from "./_${options.name}-web/${options.name}.astro";
---
${document ? "<Page />" : '<!doctype html>\n<html lang="en">\n  <head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /></head>\n  <body><Page /></body>\n</html>'}
`;
  const output = resolve(options.out),
    helper = webPageOutput(options);
  return [
    ...artifacts.map((artifact) =>
      artifact.root === helper ? { ...artifact, root: output } : artifact,
    ),
    {
      path: join(output, "index.astro"),
      root: output,
      content,
      isOwned: generatedText(
        "---\n// Code generated by astro-fyne. DO NOT EDIT.",
      ),
    },
  ];
}
