interface Entry {
  name: string;
  source: string;
  export?: string;
  output: string;
  measurements?: string;
  publicDir?: string;
  fonts?: FontFace[];
  portableProgram?: boolean;
  profile?: { state: string; width: number; height: number; scale: number };
}
interface Config {
  schema: 1;
  package: string;
  entries: Entry[];
}
interface Options {
  config: string;
  entry?: string;
  measurements?: string;
  check: boolean;
  analyze?: boolean;
}

const generatedHeader = "// Code generated by astro-fyne. DO NOT EDIT.\n";

function readConfig(value: unknown, root: string): Config {
  if (!value || typeof value !== "object")
    throw new Error("Configuration must be a JSON object.");
  const config = value as Partial<Config>;
  if (
    config.schema !== 1 ||
    !Array.isArray(config.entries) ||
    !config.entries.length
  )
    throw new Error(
      "Configuration requires schema: 1 and a nonempty entries array.",
    );
  if (
    typeof config.package !== "string" ||
    !/^[A-Za-z][A-Za-z0-9_]*$/.test(config.package)
  )
    throw new Error("package must be a Go identifier.");
  const names = new Set<string>();
  const outputs = new Set<string>();
  for (const entry of config.entries) {
    if (
      !entry ||
      typeof entry !== "object" ||
      typeof entry.name !== "string" ||
      !/^[A-Za-z][A-Za-z0-9_]*$/.test(entry.name) ||
      typeof entry.source !== "string" ||
      !entry.source ||
      typeof entry.output !== "string" ||
      !entry.output.endsWith(".gen.go")
    )
      throw new Error(
        "Each entry requires name, source and an output ending in .gen.go.",
      );
    if (entry.export !== undefined && typeof entry.export !== "string")
      throw new Error(`${entry.name}: export must be a string.`);
    if (
      entry.measurements !== undefined &&
      typeof entry.measurements !== "string"
    )
      throw new Error(`${entry.name}: measurements must be a path.`);
    if (entry.publicDir !== undefined && typeof entry.publicDir !== "string")
      throw new Error(`${entry.name}: publicDir must be a path.`);
    if (entry.fonts !== undefined) validateFontFaces(entry.fonts);
    if (
      entry.portableProgram !== undefined &&
      typeof entry.portableProgram !== "boolean"
    )
      throw new Error(`${entry.name}: portableProgram must be a Boolean.`);
    if (entry.profile !== undefined) {
      const profile = entry.profile;
      if (
        !profile ||
        typeof profile !== "object" ||
        typeof profile.state !== "string" ||
        !profile.state ||
        ![profile.width, profile.height, profile.scale].every(
          (number) =>
            typeof number === "number" && Number.isFinite(number) && number > 0,
        )
      )
        throw new Error(
          `${entry.name}: profile requires state and positive dimensions and scale.`,
        );
    }
    const output = resolve(root, entry.output);
    if (names.has(entry.name))
      throw new Error("Duplicate entry names in one Go package.");
    if (outputs.has(output)) throw new Error(`Duplicate output: ${output}`);
    if (output === join(dirname(output), "astro_fyne_scope.gen.go"))
      throw new Error(
        "astro_fyne_scope.gen.go is reserved for the compiler helper.",
      );
    names.add(entry.name);
    outputs.add(output);
  }
  return config as Config;
}

export async function generate(options: Options): Promise<void> {
  const configPath = resolve(options.config);
  const root = dirname(configPath);
  const config = readConfig(
    await readCLIJSON(
      configPath,
      "Configuration",
      "Create astro-fyne.json or pass --config <path>.",
    ),
    root,
  );
  const entries = options.entry
    ? config.entries.filter((entry) => entry.name === options.entry)
    : config.entries;
  if (!entries.length) throw new Error(`Unknown entry: ${options.entry}`);
  if (options.measurements && entries.length !== 1)
    throw new Error(
      "--measurements requires --entry when the configuration contains multiple entries.",
    );
  const outputs = new Map<string, string>();
  const analyses: {
    name: string;
    sourceHash: string;
    program: Awaited<ReturnType<typeof compile>>;
  }[] = [];
  const reports: { path: string; text: string }[] = [];
  for (const entry of entries) {
    const program = await compile(resolve(root, entry.source), entry.export, {
      root,
      ...(entry.publicDir ? { publicDir: entry.publicDir } : {}),
      ...(entry.fonts ? { fonts: entry.fonts } : {}),
    });
    if (options.analyze) {
      analyses.push({
        name: entry.name,
        sourceHash: sourceHash(program),
        program,
      });
      continue;
    }
    const measurementPath = options.measurements ?? entry.measurements;
    const measurements = measurementPath
      ? ((await readCLIJSON(
          resolve(root, measurementPath),
          "Measurements",
        )) as Measurements)
      : undefined;
    if (measurementPath) validateMeasurements(measurements);
    const output = resolve(root, entry.output);
    if (!output.endsWith(".go"))
      throw new Error(`${output}: output must end in .go.`);
    if (outputs.has(output)) throw new Error(`Duplicate output: ${output}`);
    const code = emitGo(program, {
      name: entry.name,
      packageName: config.package,
      ...(entry.profile ? { profile: entry.profile } : {}),
      ...(measurements ? { measurements } : {}),
      ...(entry.portableProgram ? { portableProgram: true } : {}),
    });
    const formatted = spawnSync("gofmt", [], {
      input: code,
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
    });
    if (formatted.error)
      throw new Error(
        `Cannot run gofmt: ${formatted.error.message}. gofmt must be on PATH and output must not exceed 256 MiB.`,
      );
    if (formatted.status !== 0)
      throw new Error(`Invalid generated Go: ${formatted.stderr}`);
    outputs.set(output, formatted.stdout);
    const report = {
      schema: 1,
      generator: "astro-fyne",
      name: entry.name,
      sourceHash: sourceHash(program),
      sources: program.sources,
      resources: (program.resources ?? []).map(
        ({ content: _content, ...resource }) => resource,
      ),
      ...(program.fonts?.length
        ? { fonts: program.fonts.map(({ content: _content, ...face }) => face) }
        : {}),
      actions: program.actions,
      components: program.components.map((component) => component.name),
      compatibility: "declarative-stage-1",
      ...(entry.portableProgram
        ? {
            portableProgram: {
              schema: 1,
              exportMethod: "ExportProgram",
              state: "declared-state-and-list-identities",
            },
          }
        : {}),
      visual: {
        measured: Boolean(measurements),
        pixelPerfectVerified: false,
        ...(measurements
          ? { state: measurements.state, viewport: measurements.viewport }
          : {}),
      },
    };
    reports.push({
      path: output.replace(/\.go$/, ".report.json"),
      text: JSON.stringify(report, null, 2) + "\n",
    });
    if (program.fonts?.length) {
      const cssPath = output.replace(/\.go$/, ".fonts.css");
      const cssHeader = "/* Code generated by astro-fyne. DO NOT EDIT. */\n";
      reports.push({
        path: cssPath,
        text:
          cssHeader +
          "/* SPDX-License-Identifier: Apache-2.0 */\n" +
          fontsCSS(program.fonts),
      });
    }
  }
  if (options.analyze) {
    process.stdout.write(
      JSON.stringify(
        analyses.length === 1 ? analyses[0] : { schema: 1, entries: analyses },
        null,
        2,
      ) + "\n",
    );
    return;
  }
  const directories = new Set([...outputs.keys()].map(dirname));
  for (const directory of directories) {
    const formatted = spawnSync("gofmt", [], {
      input: `// Code generated by astro-fyne. DO NOT EDIT.\n// SPDX-License-Identifier: Apache-2.0\npackage ${config.package}\nimport webui "github.com/thinkddr/astro-fyne/native"\n${scopeHelper}`,
      encoding: "utf8",
    });
    if (formatted.status !== 0)
      throw new Error(`Invalid generated Go helper: ${formatted.stderr}`);
    outputs.set(join(directory, "astro_fyne_scope.gen.go"), formatted.stdout);
  }
  // Parse and format every entry before any write; unsupported source leaves existing output intact.
  await applyArtifacts(
    [
      ...[...outputs].map(([path, content]) => ({
        path,
        content,
        isOwned: generatedText(generatedHeader),
      })),
      ...reports.map(({ path, text }) => ({
        path,
        content: text,
        isOwned: path.endsWith(".css")
          ? generatedText("/* Code generated by astro-fyne. DO NOT EDIT. */\n")
          : generatedJSON,
      })),
    ],
    { check: options.check },
  );
  process.stdout.write(
    `${options.check ? "Checked" : "Generated"} ${entries.length} ${entries.length === 1 ? "entry" : "entries"}; visual fidelity requires comparing captures.\n`,
  );
}

async function treeFingerprint(root: string): Promise<string> {
  const paths: string[] = [];
  async function scan(directory: string): Promise<void> {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (
        ["node_modules", ".git", "dist", ".astro", "artifacts"].includes(
          entry.name,
        )
      )
        continue;
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await scan(path);
      else if (
        /\.(astro|tsx|ts|css|json|png|jpg|jpeg|ttf)$/i.test(entry.name) &&
        !entry.name.endsWith(".report.json")
      )
        paths.push(path);
    }
  }
  await scan(root);
  const { createHash } = await import("node:crypto");
  const hash = createHash("sha256");
  for (const path of paths.sort()) {
    hash.update(path);
    hash.update(await readFile(path));
  }
  return hash.digest("hex");
}

export async function main(args = process.argv.slice(2)): Promise<void> {
  const argv = [...args];
  const name = argv.shift();
  if (!name || name === "--help" || name === "-h" || name === "help") {
    if (name === "help" && argv.length > 1)
      throw usageError("help accepts at most one command.");
    if ((name === "--help" || name === "-h") && argv.length)
      throw usageError("Use help <command> for command-specific help.");
    const selected =
      name === "help" && argv[0] ? resolveCommand(argv[0]) : undefined;
    if (name === "help" && argv[0] && !selected)
      throw usageError(`Unknown command: ${argv[0]}`);
    process.stdout.write(helpText(selected));
    return;
  }
  const command = resolveCommand(name);
  if (!command) throw usageError(`Unknown command: ${name}`);
  if (wantsHelp(argv)) {
    process.stdout.write(helpText(command));
    return;
  }
  if (argv.includes("--program")) {
    if (!["generate", "check", "reverse"].includes(command))
      throw usageError(
        "Program input supports to-fyne, to-web and check.",
        command,
      );
    const { programMain } = await import("./program-cli.ts");
    await programMain(
      argv,
      command === "reverse" ? "web" : "native",
      command === "check",
    );
    return;
  }
  if (command === "reverse") {
    const { reverseMain } = await import("./reverse-cli.js");
    await reverseMain(argv);
    return;
  }
  if (argv.includes("--scene")) {
    if (!["generate", "check"].includes(command))
      throw usageError(
        "Scene input supports to-fyne/generate and check.",
        command,
      );
    const { nativeSceneMain } = await import("./scene-native-cli.ts");
    await nativeSceneMain(argv, command === "check");
    return;
  }
  const options: Options = {
    config: "astro-fyne.json",
    check: command === "check",
    analyze: command === "analyze",
  };
  const seen = new Set<string>();
  while (argv.length) {
    const flag = argv.shift()!;
    if (!["--config", "--entry", "--measurements"].includes(flag))
      throw usageError(`Unknown option: ${flag}`, command);
    if (seen.has(flag)) throw usageError(`Duplicate option: ${flag}`, command);
    seen.add(flag);
    const value = argv.shift();
    if (!value || value.startsWith("-"))
      throw usageError(`Missing value for ${flag}.`, command);
    if (flag === "--config") options.config = value;
    else if (flag === "--entry") options.entry = value;
    else if (flag === "--measurements") options.measurements = value;
  }
  await generate(options);
  if (command !== "watch") return;
  const root = dirname(resolve(options.config));
  let previous = await treeFingerprint(root);
  // Recursive fs.watch differs between OSes. Content hashes also catch atomic saves.
  for (;;) {
    await new Promise((done) => setTimeout(done, 500));
    const current = await treeFingerprint(root);
    if (current === previous) continue;
    previous = current;
    try {
      await generate({ ...options, check: false });
    } catch (error) {
      process.stderr.write(
        `${error instanceof Error ? error.message : error}\n`,
      );
    }
  }
}

if (import.meta.main)
  main().catch((error: unknown) => {
    process.stderr.write(
      `${error instanceof Error ? error.message : String(error)}\n`,
    );
    process.exitCode = 1;
  });
