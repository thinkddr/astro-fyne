const header =
  "// Code generated by astro-fyne. DO NOT EDIT.\n// SPDX-License-Identifier: Apache-2.0\n";
const literal = (value: unknown) =>
  JSON.stringify(value)
    .replaceAll("<", "\\u003c")
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029")
    .replaceAll("\ufeff", "\\ufeff");
export interface CatalogueOptions {
  catalogue: string;
  out: string;
  name: string;
  direction: "native" | "web";
  packageName?: string;
  publicDir?: string;
  actionsModule?: string;
  check?: boolean;
}
function formattedGo(source: string) {
  const result = spawnSync("gofmt", [], {
    input: source,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  if (result.error || result.status !== 0)
    throw new Error(
      `Cannot format catalogue: ${result.error?.message ?? result.stderr}`,
    );
  return result.stdout;
}
function innerModule(module?: string) {
  return module?.startsWith(".") ? `../${module}` : module;
}
function localModule(module: string) {
  if (
    !module ||
    /[\u0000-\u001f<>\\]/.test(module) ||
    /^[A-Za-z][A-Za-z\d+.-]*:/.test(module) ||
    module.startsWith("//")
  )
    throw new Error("actions-module requires a local or package import");
}

function catalogueLayoutCSS(style: SceneSourceStyle) {
  const result = sourceStyleCSS(style);
  result.opacity = style.opacity;
  for (const name of ["fontStyle", "textAlign", "whiteSpace"] as const)
    if (style[name]) result[name] = style[name];
  for (const name of ["fontSize", "fontWeight"] as const)
    if (style[name]) result[name] = style[name];
  if (style.lineHeight) result.lineHeight = `${style.lineHeight}px`;
  return result;
}

function hasLabelReference(nodes: SceneNode[]): boolean {
  return nodes.some(
    (node) => !!node.labelFor || hasLabelReference(node.children),
  );
}

/** Prepare the complete library before touching the destination. */
export async function prepareCatalogue(options: CatalogueOptions) {
  if (
    !/^[A-Z][A-Za-z0-9_]*$/.test(options.name) ||
    !/^[A-Za-z][A-Za-z0-9_]*$/.test(options.packageName ?? "generated")
  )
    throw new Error("Catalogue name/package must be Go identifiers");
  if (options.actionsModule) localModule(options.actionsModule);
  if (
    (options.direction === "native" &&
      (options.actionsModule || options.publicDir)) ||
    (options.direction === "web" && options.packageName)
  )
    throw new Error(
      "Use --package for native catalogues and --actions-module/--public-dir for web catalogues",
    );
  const input = resolve(options.catalogue),
    output = resolve(options.out);
  const source = new TextDecoder("utf-8", {
      fatal: true,
      ignoreBOM: true,
    }).decode(await readFile(input)),
    spec = await parseCatalogue(source);
  if (options.direction === "web" && spec.islands.length > 1) {
    const declared = new Set(spec.islands.map((island) => island.component));
    for (const component of spec.components)
      if (
        component.kind === "scene" &&
        declared.has(component.id) &&
        hasLabelReference(
          validateSceneDocument(JSON.parse(component.payload)).roots,
        )
      )
        throw new Error(
          `Catalogue web scene ${JSON.stringify(component.id)} uses labelFor and requires a single declared island until document-wide scene ID scoping is supported`,
        );
  }
  const artifacts: Artifact[] = [];
  const text = (
    path: string,
    content: string,
    marker = header.split("\n")[0]!,
  ) =>
    artifacts.push({
      path: join(output, path),
      root: output,
      content,
      isOwned: generatedText(marker),
    });
  const exact = (path: string, content: Uint8Array | string, root = output) =>
    artifacts.push({
      path: join(root, path),
      root,
      content,
      isOwned: (saved) => Buffer.from(saved).equals(Buffer.from(content)),
    });
  const fontCSS = spec.fontFaces
    .map(
      (face) =>
        `@font-face{font-family:"${face.family}";font-weight:${face.weight};font-style:${face.style};font-display:block;src:url("./${options.name}.catalogue-assets/${face.hash}.ttf") format("truetype");}`,
    )
    .join("\n");
  for (const resource of spec.resources) {
    const suffix =
      resource.mediaType === "font/ttf"
        ? "ttf"
        : resource.mediaType === "image/png"
          ? "png"
          : resource.mediaType === "image/jpeg"
            ? "jpg"
            : resource.mediaType === "text/css"
              ? "css"
              : "bin";
    exact(
      `${options.name}.catalogue-assets/${resource.hash}.${suffix}`,
      catalogueBytes(resource.content, 20 * 1024 * 1024),
    );
    exact(
      `${options.name}.catalogue-assets/${resource.hash}.${suffix}.license.txt`,
      resource.license,
    );
  }
  for (const sheet of spec.stylesheets)
    exact(
      `${options.name}.css-sources/${sheet.hash}.css`,
      catalogueBytes(sheet.content, 16 * 1024 * 1024, true),
    );
  text(
    `${options.name}.fonts.css`,
    "/* Code generated by astro-fyne. DO NOT EDIT. */\n/* SPDX-License-Identifier: Apache-2.0 */\n" +
      fontCSS +
      "\n",
    "/* Code generated by astro-fyne. DO NOT EDIT. */",
  );
  const archiveFile = `${options.name}.catalogue-sources/${catalogueHash(source)}.json`;
  exact(archiveFile, source);
  const publicDir = resolve(options.publicDir ?? join(output, "public"));
  if (options.direction === "web") {
    const faces = new Map<string, string>();
    const bind = (
      family: string,
      weight: number,
      style: string,
      hash: string,
    ) => {
      const key = `${family.toLowerCase()}:${weight}:${style}`;
      if (faces.has(key) && faces.get(key) !== hash)
        throw new Error(`Catalogue web font collision: ${key}`);
      faces.set(key, hash);
    };
    for (const face of spec.fontFaces)
      bind(face.family, face.weight, face.style, face.hash);
    for (const component of spec.components)
      if (component.kind === "program")
        for (const face of validateProgramArchive(JSON.parse(component.payload))
          .program.fonts ?? [])
          bind(face.family, face.weight, face.style, face.hash);
  }
  const registrations: string[] = [],
    imports: string[] = [],
    exported: string[] = [];
  const componentNames = new Map<string, string>();
  async function prepareComponent(component: CatalogueComponent, name: string) {
    const document: unknown = JSON.parse(component.payload);
    const packageName = options.packageName ?? "generated";
    if (component.kind === "javascript") {
      if (options.direction === "native") return;
      const prepared = await prepareJavascript({
        archive: await validateJavascriptArchive(document),
        out: output,
        name,
        direction: "web",
        ...(options.actionsModule
          ? { actionsModule: innerModule(options.actionsModule) }
          : {}),
      });
      artifacts.push(...prepared.artifacts);
      imports.push(`import ${name} from "./_${name}-javascript/${name}.tsx";`);
    } else if (component.kind === "program") {
      const { archive, program } = validateProgramArchive(document);
      if (options.direction === "native") {
        text(
          `${name}.gen.go`,
          formattedGo(
            emitGo(program, {
              name,
              packageName,
              portableProgram: true,
              restoreProgram: JSON.stringify(archive),
            }),
          ),
        );
        text(
          "astro_fyne_scope.gen.go",
          formattedGo(
            `${header}package ${packageName}\nimport webui "github.com/thinkddr/astro-fyne/native"\n${scopeHelper}`,
          ),
        );
        const initial = program.fonts?.length
          ? `backend:=New${name}Backend();if err:=merge${options.name}Fonts(&backend,input.Backend);err!=nil{return nil,err}`
          : "backend:=input.Backend";
        registrations.push(
          `if err:=registry.RegisterFactory(${literal(component.id)},func(input catalog.Instance)(fyne.Widget,error){${initial};return New${name}(nil,input.Actions,backend)});err!=nil{return nil,err}`,
        );
      } else {
        const result = await emitWebProgram(program, archive, {
          name,
          ...(options.actionsModule
            ? { actionsModule: innerModule(options.actionsModule) }
            : {}),
        });
        for (const [file, content] of Object.entries(result.files))
          text(
            file,
            content,
            file.endsWith(".astro")
              ? "---\n// Code generated by astro-fyne. DO NOT EDIT."
              : file.endsWith(".css")
                ? "/* Code generated by astro-fyne. DO NOT EDIT. */"
                : undefined,
          );
        for (const asset of result.assets)
          exact(asset.path, asset.content, publicDir);
        imports.push(
          `import ${name} from "./_${name}-program/${name}.tsx";`,
          `import "./${name}.fonts.css";`,
        );
      }
    } else {
      if (options.direction === "native") {
        const result = emitNativeScene(document, { name, packageName });
        text(`${name}.gen.go`, formattedGo(result.code));
        registrations.push(
          `if err:=registry.RegisterFactory(${literal(component.id)},func(input catalog.Instance)(fyne.Widget,error){return New${name}(nil,input.Actions,input.Backend)});err!=nil{return nil,err}`,
        );
      } else {
        const result = emitWebScene(document, {
          name,
          ...(options.actionsModule
            ? { actionsModule: options.actionsModule }
            : {}),
        });
        text(`${name}.tsx`, result.preact);
        text(
          `${name}.css`,
          result.css,
          "/* Code generated by astro-fyne. DO NOT EDIT.",
        );
        for (const asset of result.assets)
          exact(asset.path, asset.content, publicDir);
        imports.push(
          `import ${name} from "./${name}.tsx";`,
          `import "./${name}.css";`,
        );
      }
    }
  }
  for (const [index, component] of spec.components.entries()) {
    const name = `${options.name}Component${index}`;
    componentNames.set(component.id, name);
    await prepareComponent(component, name);
    if (options.direction === "web")
      exported.push(`${literal(component.id)}:${name}`);
  }
  if (options.direction === "native") {
    text(
      `${options.name}.catalogue.gen.go`,
      formattedGo(`${header}package ${options.packageName ?? "generated"}
import("bytes";"fmt";"fyne.io/fyne/v2";webui "github.com/thinkddr/astro-fyne/native";"github.com/thinkddr/astro-fyne/native/catalog")
const ${options.name}CatalogueArchive=${literal(source)}
func New${options.name}Catalogue()(*catalog.Registry,error){registry,err:=catalog.Parse([]byte(${options.name}CatalogueArchive));if err!=nil{return nil,err};${registrations.join(";")};return registry,nil}
func merge${options.name}Fonts(target *webui.FyneBackend,extra webui.FyneBackend)error{if target.Fonts==nil{target.Fonts=map[string]map[webui.Font]fyne.Resource{}};for family,faces:=range extra.Fonts{if target.Fonts[family]==nil{target.Fonts[family]=map[webui.Font]fyne.Resource{}};for face,resource:=range faces{if old:=target.Fonts[family][face];old!=nil&&!bytes.Equal(old.Content(),resource.Content()){return fmt.Errorf("catalogue: conflicting font face %s",family)};target.Fonts[family][face]=resource}};return nil}
`),
    );
  } else {
    const islandNames: string[] = [];
    for (const [index, island] of spec.islands.entries()) {
      let name = componentNames.get(island.component)!;
      if (island.statePayload) {
        name = `${options.name}Island${index}`;
        const prototype = spec.components.find(
          (component) => component.id === island.component,
        )!;
        await prepareComponent(
          {
            ...prototype,
            payload: island.statePayload,
            hash: island.stateHash!,
          },
          name,
        );
      }
      islandNames.push(`${literal(island.id)}:${name}`);
    }
    for (const file of [
      "catalogue-types.ts",
      "catalogue-web.ts",
      "motion.ts",
      "javascript-types.ts",
    ])
      text(
        `_${options.name}-catalogue/${file}`,
        header + (await readFile(new URL(file, import.meta.url), "utf8")),
      );
    imports.push(
      `import {createCatalogueExporter} from "./_${options.name}-catalogue/catalogue-web.ts";`,
      `import type {CatalogueSpec} from "./_${options.name}-catalogue/catalogue-types.ts";`,
    );
    if (spec.motions?.length) {
      for (const file of ["motion-web.ts"])
        text(
          `_${options.name}-catalogue/${file}`,
          header + (await readFile(new URL(file, import.meta.url), "utf8")),
        );
      imports.push(
        `import type {MotionSpec} from "./_${options.name}-catalogue/motion.ts";`,
        `export {WebMotionController} from "./_${options.name}-catalogue/motion-web.ts";`,
      );
    }
    const themes = Object.fromEntries(
      spec.themes.map((theme) => [theme.id, theme.tokens]),
    );
    const layouts = Object.fromEntries(
      spec.layouts.map((layout) => [
        layout.id,
        catalogueLayoutCSS(layout.style),
      ]),
    );
    text(
      `${options.name}.catalogue.tsx`,
      `${header}import {h,type ComponentType,type Ref} from "preact";\n${imports.join("\n")}\nimport "./${options.name}.fonts.css";
export const catalogue=JSON.parse(${literal(source)}) as CatalogueSpec;
export const exportCatalogue=createCatalogueExporter(${literal(source)});
export const themes=${literal(themes)};
export const layouts=${literal(layouts)};
export const motions${spec.motions?.length ? ":MotionSpec[]" : ""}=${literal(spec.motions ?? [])};
export const components={${exported.join(",")}};
const islandComponents:Record<string,ComponentType<any>>={${islandNames.join(",")}};
export interface ${options.name}IslandProps{id:string;actions?:Record<string,(...args:any[])=>any>;handleRef?:Ref<any>;}
export function ${options.name}Island({id,actions,handleRef}:${options.name}IslandProps){if(!Object.hasOwn(islandComponents,id))throw new Error("Unknown catalogue island: "+id);const Component=islandComponents[id];if(!Component)throw new Error("Unknown catalogue island: "+id);return h(Component,{actions,ref:handleRef,key:id});}
`,
    );
    text(
      `${options.name}.astro`,
      `---\n${header}import {${options.name}Island} from "./${options.name}.catalogue.tsx";\n---\n${spec.islands.map((island) => `<${options.name}Island id=${literal(island.id)} client:only="preact" />`).join("\n")}\n`,
      "---\n// Code generated by astro-fyne. DO NOT EDIT.",
    );
  }
  const report = {
    schema: 1,
    generator: "astro-fyne",
    kind: "catalogue-generation",
    name: options.name,
    catalogueName: spec.name,
    sourceHash: catalogueHash(source),
    archiveFile,
    direction: options.direction,
    components: spec.components.map(({ id, kind, hash }) => ({
      id,
      kind,
      hash,
    })),
    islands: spec.islands.map(({ id, component, key }) => ({
      id,
      component,
      key,
    })),
    resources: spec.resources.map(
      ({ content: _content, ...resource }) => resource,
    ),
    stylesheetSources: spec.stylesheets.map(
      ({ content: _content, ...sheet }) => sheet,
    ),
    visual: { pixelPerfectVerified: false },
    limitations: [
      "Named themes and layouts are explicit host dependencies, not automatic style overrides",
      "Scene components retain snapshot IDs; scenes with labelFor require a single declared island and globally unique host IDs",
      "Motion definitions require an explicit target binding and clock",
      "Arbitrary Go functions and unsupported CSS require platform adapters",
    ],
  };
  artifacts.push({
    path: join(output, `${options.name}.catalogue.report.json`),
    root: output,
    content: JSON.stringify(report, null, 2) + "\n",
    isOwned: generatedJSON,
  });
  if (artifacts.some((artifact) => resolve(artifact.path) === input))
    throw new Error("Catalogue output cannot replace its input");
  // Multiple declarative components share the same generated helper and assets.
  const unique = new Map<string, Artifact>();
  for (const artifact of artifacts) {
    const path = resolve(artifact.path),
      previous = unique.get(path);
    if (
      previous &&
      !Buffer.from(previous.content).equals(Buffer.from(artifact.content))
    )
      throw new Error(`Catalogue output collision: ${path}`);
    unique.set(path, artifact);
  }
  return { spec, artifacts: [...unique.values()] };
}
export async function generateCatalogue(options: CatalogueOptions) {
  const result = await prepareCatalogue(options);
  await applyArtifacts(result.artifacts, { check: options.check ?? false });
  process.stdout.write(
    `${options.check ? "Checked" : "Generated"} ${options.name}: catalogue → ${options.direction === "native" ? "Fyne Go" : "Astro + Preact + CSS"}.\n`,
  );
  return result.spec;
}
export async function catalogueMain(
  args: readonly string[],
  direction: "native" | "web",
  check = false,
) {
  const options: Partial<CatalogueOptions> = { direction, check },
    seen = new Set<string>(),
    argv = [...args];
  while (argv.length) {
    const flag = argv.shift()!;
    if (seen.has(flag)) throw usageError(`Duplicate catalogue option: ${flag}`);
    seen.add(flag);
    if (flag === "--check") {
      options.check = true;
      continue;
    }
    if (
      ![
        "--catalogue",
        "--out",
        "--name",
        "--package",
        "--public-dir",
        "--actions-module",
      ].includes(flag)
    )
      throw usageError(`Unknown catalogue option: ${flag}`);
    const value = argv.shift();
    if (!value || value.startsWith("-"))
      throw usageError(`Missing value for ${flag}`);
    if (flag === "--catalogue") options.catalogue = value;
    else if (flag === "--out") options.out = value;
    else if (flag === "--name") options.name = value;
    else if (flag === "--package") options.packageName = value;
    else if (flag === "--public-dir") options.publicDir = value;
    else options.actionsModule = value;
  }
  if (!options.catalogue || !options.out || !options.name)
    throw usageError(
      "Catalogue conversion needs --catalogue, --out and --name",
    );
  await generateCatalogue(options as CatalogueOptions);
}
