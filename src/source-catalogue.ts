import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";
import { applyArtifacts, generatedJSON, generatedText } from "./artifacts.ts";
import { prepareCatalogueSource } from "./catalogue-cli.ts";
import { catalogueHash, type CatalogueSpec } from "./catalogue.ts";
import { readCLIJSON } from "./cli-help.ts";
import { prepareJavascriptBundle } from "./javascript.ts";
import { loadLicensedFonts } from "./licensed-fonts.ts";

export interface SourceCatalogueOptions {
  source: string;
  fonts: string;
  out: string;
  name: string;
  selected?: string;
  props?: string;
  stylesheet?: string;
  actions?: string[];
  packageName?: string;
  check?: boolean;
}
const header =
  "// Code generated by astro-fyne. DO NOT EDIT.\n// SPDX-License-Identifier: Apache-2.0\n";

function constructors(name: string, packageName: string) {
  const source = `${header}package ${packageName}
import("encoding/json";"errors";"fyne.io/fyne/v2";webui "github.com/thinkddr/astro-fyne/native";"github.com/thinkddr/astro-fyne/native/catalog";jsruntime "github.com/thinkddr/astro-fyne/native/javascript")
type ${name}Widget = jsruntime.Widget
func New${name}(props webui.Scope,actions webui.Actions)(*${name}Widget,error){return New${name}WithOptions(props,actions,jsruntime.Options{})}
func New${name}WithOptions(props webui.Scope,actions webui.Actions,options jsruntime.Options)(*${name}Widget,error){
 registry,err:=New${name}Catalogue();if err!=nil{return nil,err}
 err=registry.RegisterFactory("app",func(input catalog.Instance)(fyne.Widget,error){
  var archive jsruntime.Archive;if err:=json.Unmarshal([]byte(input.Component.Payload),&archive);err!=nil{return nil,err}
  if len(props)>0{if len(archive.Events)>0||len(archive.Journal)>0||archive.Frame!=nil{return nil,errors.New("javascript: replay requires original props; regenerate source to replace them")};data,err:=json.Marshal(props);if err!=nil{return nil,err};archive.Props=data}
  return jsruntime.NewWithOptions(archive,input.Actions,options,input.Backend)
 });if err!=nil{return nil,err};object,err:=registry.NewIsland("app",actions);if err!=nil{return nil,err};widget,ok:=object.(*jsruntime.Widget);if !ok{return nil,errors.New("catalogue: source constructor requires a JavaScript widget")};return widget,nil
}
func Export${name}Catalogue(widget *${name}Widget)([]byte,error){
 if widget==nil{return nil,errors.New("catalogue: export requires a widget")};archive,err:=widget.ExportJavascript();if err!=nil{return nil,err};payload,err:=json.Marshal(archive);if err!=nil{return nil,err};registry,err:=New${name}Catalogue();if err!=nil{return nil,err};updated,err:=registry.WithIslandState("app",string(payload));if err!=nil{return nil,err};return updated.Marshal()
}
`;
  const formatted = spawnSync("gofmt", [], {
    input: source,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  if (formatted.error || formatted.status !== 0)
    throw new Error(
      `Cannot format source catalogue: ${formatted.error?.message ?? formatted.stderr}`,
    );
  return formatted.stdout;
}

/** Prepare one source island and all licensed resources before output writes. */
export async function prepareSourceCatalogue(options: SourceCatalogueOptions) {
  const snapshot = {
    ...options,
    actions: options.actions ? [...options.actions] : undefined,
  };
  if (
    !/^[A-Z][A-Za-z0-9_]*$/.test(snapshot.name) ||
    !/^[A-Za-z][A-Za-z0-9_]*$/.test(snapshot.packageName ?? "generated")
  )
    throw new Error("JavaScript widget name/package must be Go identifiers");
  const source = resolve(snapshot.source),
    manifest = resolve(snapshot.fonts),
    out = resolve(snapshot.out),
    propsFile = snapshot.props ? resolve(snapshot.props) : undefined,
    stylesheet = snapshot.stylesheet ? resolve(snapshot.stylesheet) : undefined,
    protectedInputs = new Set([
      source,
      manifest,
      ...(propsFile ? [propsFile] : []),
    ]),
    fonts = await loadLicensedFonts(manifest),
    bundle = await prepareJavascriptBundle(
      source,
      snapshot.selected,
      propsFile
        ? ((await readCLIJSON(propsFile, "JavaScript props")) as Record<
            string,
            unknown
          >)
        : {},
      snapshot.actions ?? [],
      stylesheet ? [stylesheet] : [],
    );
  for (const input of [...fonts.inputPaths, ...bundle.inputPaths])
    protectedInputs.add(input);
  const archive = bundle.archive,
    payload = JSON.stringify(archive),
    stylesheets = (archive.stylesheets ?? []).map((sheet, index) => ({
      id: `css${index}`,
      path: sheet.path,
      hash: sheet.hash,
      content: Buffer.from(sheet.text).toString("base64"),
    })),
    spec: CatalogueSpec = {
      schema: 1,
      kind: "astro-fyne-catalogue",
      name: snapshot.name,
      resources: fonts.resources,
      stylesheets,
      fontFaces: fonts.fontFaces,
      themes: [],
      layouts: [],
      components: [
        {
          id: "app",
          kind: "javascript",
          payload,
          hash: catalogueHash(payload),
          stylesheets: stylesheets.map((sheet) => sheet.id),
          fontFaces: fonts.fontFaces.map((face) => face.id),
          actions: [...archive.actions],
        },
      ],
      islands: [{ id: "app", component: "app", key: "app" }],
    },
    catalogueSource = JSON.stringify(spec, null, 2) + "\n",
    inputPaths = [...protectedInputs].sort(),
    prepared = await prepareCatalogueSource(catalogueSource, {
      out,
      name: snapshot.name,
      direction: "native",
      ...(snapshot.packageName ? { packageName: snapshot.packageName } : {}),
      protectedInputs: inputPaths,
    });
  prepared.artifacts.push({
    path: join(out, `${snapshot.name}.gen.go`),
    root: out,
    content: constructors(snapshot.name, snapshot.packageName ?? "generated"),
    isOwned: generatedText(header.split("\n")[0]!),
  });
  prepared.artifacts.push({
    path: join(out, `${snapshot.name}.source-fonts.report.json`),
    root: out,
    content:
      JSON.stringify(
        {
          schema: 1,
          generator: "astro-fyne",
          kind: "source-font-catalogue",
          name: snapshot.name,
          catalogueHash: catalogueHash(catalogueSource),
          archiveFile: `${snapshot.name}.catalogue-sources/${catalogueHash(catalogueSource)}.json`,
          manifestHash: fonts.manifestHash,
          fontFaces: fonts.bindings,
          constructor: `New${snapshot.name}`,
          optionsConstructor: `New${snapshot.name}WithOptions`,
          exportFunction: `Export${snapshot.name}Catalogue`,
          island: "app",
          strictFontAdmissionEnabled: false,
          visual: { pixelPerfectVerified: false },
        },
        null,
        2,
      ) + "\n",
    isOwned: generatedJSON,
  });
  return { ...prepared, archive, inputPaths };
}

export async function generateSourceCatalogue(options: SourceCatalogueOptions) {
  const snapshot = {
      ...options,
      actions: options.actions ? [...options.actions] : undefined,
    },
    prepared = await prepareSourceCatalogue(snapshot);
  await applyArtifacts(prepared.artifacts, {
    check: snapshot.check ?? false,
    protectedInputs: prepared.inputPaths,
  });
  process.stdout.write(
    `${snapshot.check ? "Checked" : "Generated"} ${snapshot.name}: source + licensed fonts → native Fyne catalogue.\n`,
  );
  return prepared.spec;
}
